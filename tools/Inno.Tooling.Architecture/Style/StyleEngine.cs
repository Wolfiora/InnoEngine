using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Inno.Tooling.Architecture;

// Checks handwritten C# against the style rulebook and applies the automatic fixes.
internal static class StyleEngine
{
    private const int C_MAX_ROUNDS = 40;

    private const string C_GENERATED_HEADER = "<auto-generated";

    private const string C_GENERATED_ATTRIBUTE = "GeneratedCode";

    private static readonly UTF8Encoding ENCODING = new(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true);

    private static readonly string[] SKIPPED_DIRECTORIES = [".git", "bin", "obj", "extern", "artifacts", "node_modules"];

    internal static readonly IReadOnlyList<StyleRule> RULES =
    [
        new FileTextStyleRule(),
        new UsingOrderStyleRule(),
        new FileStructureStyleRule(),
        new BraceBlankLineStyleRule(),
        new MemberSpacingStyleRule(),
        new ArgumentJoinStyleRule(),
        new ArgumentListStyleRule(),
        new LineWidthStyleRule(),
        new ParameterListStyleRule(),
        new ParameterCloseStyleRule(),
        new ClauseStyleRule(),
        new ArrowMemberStyleRule(),
        new LeadingOperatorStyleRule(),
        new ChainStyleRule(),
        new SingleLineBlockStyleRule(),
        new StatementLineStyleRule(),
        new BraceListStyleRule(),
        new BraceStyleRule(),
        new EmptyBodyStyleRule(),
        new EmptyTypeStyleRule(),
        new HeaderCloseStyleRule(),
        new EmbeddedBraceStyleRule(),
        new LambdaBodyStyleRule(),
        new OperatorAlignmentStyleRule(),
        new TrailingCommaStyleRule(),
        new LocalTypeStyleRule(),
        new FieldInitializerStyleRule(),
        new EmptyStringStyleRule(),
        new LambdaParameterStyleRule(),
        new NumericLiteralStyleRule(),
        new AttributeStyleRule(),
        new DocumentationLayoutStyleRule(),
        new CommentStyleRule(),
        new AccessModifierStyleRule(),
        new ModifierOrderStyleRule(),
        new SealedClassStyleRule(),
        new RecordStructStyleRule(),
        new NamespaceStyleRule(),
        new UsingPlacementStyleRule(),
        new BuiltInTypeStyleRule(),
        new MemberOrderStyleRule()
    ];

    internal static IEnumerable<string> EnumerateSources(string root)
    {
        var pending = new Stack<string>();
        pending.Push(root);
        while (pending.Count > 0)
        {
            string directory = pending.Pop();
            foreach (string child in Directory.EnumerateDirectories(directory))
            {
                if (!SKIPPED_DIRECTORIES.Contains(Path.GetFileName(child), StringComparer.Ordinal))
                {
                    pending.Push(child);
                }
            }

            foreach (string file in Directory.EnumerateFiles(directory, "*.cs"))
            {
                yield return file;
            }
        }
    }

    // Generated and third-party sources follow their producer, not the rulebook. A marker counts only as the file
    // header comment or as an attribute, so a generator that writes the marker into its output stays handwritten.
    internal static bool IsHandwritten(
        string relativePath,
        string content
    ) {
        if (relativePath.Contains("/Generated/", StringComparison.Ordinal)) return false;
        bool hasHeader = content.Contains(C_GENERATED_HEADER, StringComparison.OrdinalIgnoreCase);
        bool hasAttribute = content.Contains(C_GENERATED_ATTRIBUTE, StringComparison.Ordinal);
        if (!hasHeader && !hasAttribute) return true;
        SyntaxNode root = new StyleSource(relativePath, content).root;
        if (hasHeader && root.GetFirstToken(includeZeroWidth: true).LeadingTrivia.Any(IsGeneratedHeader)) return false;
        return !hasAttribute || !root.DescendantNodes().OfType<AttributeSyntax>().Any(IsGeneratedAttribute);
    }

    internal static StyleReport Run(
        string root,
        IReadOnlyCollection<string> paths,
        IReadOnlyCollection<string> ruleIDs,
        bool fix
    ) {
        StyleRule[] rules = RULES.Where(rule => ruleIDs.Count == 0 || ruleIDs.Contains(rule.id)).ToArray();
        var findings = new ConcurrentBag<StyleFinding>();
        var rejections = new ConcurrentBag<StyleRejection>();
        int files = 0;
        int changedFiles = 0;
        Parallel.ForEach(
            paths,
            path =>
            {
                string relativePath = Path.GetRelativePath(root, path).Replace('\\', '/');
                string original = ENCODING.GetString(File.ReadAllBytes(path));
                if (!IsHandwritten(relativePath, original)) return;
                Interlocked.Increment(ref files);
                string content = fix ? Fix(relativePath, original, rules, rejections) : original;
                if (!string.Equals(content, original, StringComparison.Ordinal))
                {
                    File.WriteAllBytes(path, ENCODING.GetBytes(content));
                    Interlocked.Increment(ref changedFiles);
                }

                var source = new StyleSource(relativePath, content);
                var local = new List<StyleFinding>();
                foreach (StyleRule rule in rules)
                {
                    rule.Check(source, local);
                }

                foreach (StyleFinding finding in local)
                {
                    findings.Add(finding);
                }
            }
        );
        StyleFinding[] ordered = findings
            .OrderBy(static finding => finding.rule, StringComparer.Ordinal)
            .ThenBy(static finding => finding.path, StringComparer.Ordinal)
            .ThenBy(static finding => finding.line)
            .ToArray();
        StyleRejection[] rejected = rejections
            .OrderBy(static rejection => rejection.path, StringComparer.Ordinal)
            .ThenBy(static rejection => rejection.rule, StringComparer.Ordinal)
            .ToArray();
        return new StyleReport(files, changedFiles, ordered, rejected);
    }

    // Reports every finding of every rule for one source; a generated source has none.
    internal static IReadOnlyList<StyleFinding> Check(
        string relativePath,
        string content
    ) {
        var findings = new List<StyleFinding>();
        if (!IsHandwritten(relativePath, content)) return findings;
        var source = new StyleSource(relativePath, content);
        if (source.hasSyntaxErrors) return findings;
        foreach (StyleRule rule in RULES)
        {
            rule.Check(source, findings);
        }

        return findings;
    }

    // Applies every fix until the text is stable. A fix is kept only when it provably preserves the tokens.
    internal static string Fix(
        string relativePath,
        string original,
        IReadOnlyList<StyleRule> rules,
        ConcurrentBag<StyleRejection> rejections
    ) {
        string content = original;
        var rejectedRules = new HashSet<string>(StringComparer.Ordinal);
        for (int round = 0; round < C_MAX_ROUNDS; round++)
        {
            bool isChanged = false;
            foreach (StyleRule rule in rules)
            {
                if (rejectedRules.Contains(rule.id)) continue;
                var source = new StyleSource(relativePath, content);
                if (source.hasSyntaxErrors)
                {
                    rejections.Add(new(rule.id, relativePath, "The file has syntax errors."));
                    return content;
                }

                IReadOnlyList<StyleEdit> edits = rule.Fix(source);
                if (edits.Count == 0) continue;
                string updated = StyleSource.Apply(content, edits);
                if (string.Equals(updated, content, StringComparison.Ordinal)) continue;
                var candidate = new StyleSource(relativePath, updated);
                string? reason = Preservation(rule.kind, source, candidate);
                if (reason is not null)
                {
                    rejectedRules.Add(rule.id);
                    rejections.Add(new(rule.id, relativePath, reason));
                    continue;
                }

                content = updated;
                isChanged = true;
            }

            if (!isChanged) return content;
        }

        rejections.Add(new("*", relativePath, "The fixes did not converge."));
        return content;
    }

    private static bool IsGeneratedHeader(SyntaxTrivia trivia)
        => (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
           && trivia.ToString().Contains(C_GENERATED_HEADER, StringComparison.OrdinalIgnoreCase);

    private static bool IsGeneratedAttribute(AttributeSyntax attribute)
        => attribute.Name.ToString().Split('.')[^1] is "GeneratedCode" or "GeneratedCodeAttribute";

    private static string? Preservation(
        StyleRuleKind kind,
        StyleSource before,
        StyleSource after
    ) {
        if (after.hasSyntaxErrors) return "The fix introduced a syntax error.";
        if (kind == StyleRuleKind.Rewrite) return null;
        IReadOnlyList<string> expected = before.TokenTexts();
        IReadOnlyList<string> actual = after.TokenTexts();
        if (kind == StyleRuleKind.Reorder)
        {
            return expected.Order(StringComparer.Ordinal).SequenceEqual(actual.Order(StringComparer.Ordinal), StringComparer.Ordinal)
                   ? null
                   : "The fix added or removed tokens.";
        }

        return expected.SequenceEqual(actual, StringComparer.Ordinal) ? null : "The fix changed the token sequence.";
    }
}
