using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using System.Xml.Linq;
using Inno.Runtime;

namespace Inno.Build;

internal static class PlayerCodeCompositionWriter
{
    internal static async ValueTask WriteAsync(
        string playerDirectory,
        GameCodeDeployment deployment,
        CancellationToken cancellationToken
    ) {
        string project = Path.Combine(playerDirectory, "Player.csproj");
        XDocument document = XDocument.Load(project);
        string? assemblyName = document.Descendants("AssemblyName").Select(static item => item.Value).SingleOrDefault();
        if (string.IsNullOrWhiteSpace(assemblyName))
            throw new InvalidDataException("A prepared Player project must declare its assembly name explicitly.");
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        source.Append("namespace ").Append(assemblyName).Append(".Generated;\n\n")
            .Append("internal static class PlayerDeploymentDefinition\n{\n")
            .Append("    internal static global::Inno.Runtime.GameCodeDeployment CreateDeployment() => new([\n");
        foreach (GameCodeModule module in deployment.modules)
        {
            source.Append("        new global::Inno.Runtime.GameCodeModule(\n            ").Append(Quote(module.name))
                .Append(", global::Inno.Extensibility.Modules.AssemblyDomain.").Append(module.domain).Append(", [\n");
            foreach (GameCodeAssembly assembly in module.assemblies)
                source.Append("                new global::Inno.Runtime.GameCodeAssembly(").Append(Quote(assembly.name))
                    .Append(", ").Append(Quote(assembly.contentFingerprint)).Append("),\n");
            source.Append("            ], [").Append(string.Join(", ", module.dependencies.Select(Quote))).Append("]),\n");
        }
        source.Append("    ]);\n\n")
            .Append("    internal static global::System.Collections.Generic.IReadOnlyDictionary<string, global::System.Collections.Generic.IReadOnlyList<global::System.Reflection.Assembly>> CreateAssemblies() =>\n")
            .Append("        new global::System.Collections.Generic.Dictionary<string, global::System.Collections.Generic.IReadOnlyList<global::System.Reflection.Assembly>>\n        {\n");
        foreach (GameCodeModule module in deployment.modules)
        {
            source.Append("            [").Append(Quote(module.name)).Append("] = [\n");
            foreach (GameCodeAssembly assembly in module.assemblies)
                source.Append("                global::").Append(assembly.name).Append(".Generated.RuntimeModuleCatalog.assembly,\n");
            source.Append("            ],\n");
        }
        source.Append("        };\n}\n");
        await File.WriteAllTextAsync(Path.Combine(playerDirectory, "PlayerDeploymentDefinition.g.cs"),
            source.ToString(), cancellationToken).ConfigureAwait(false);
    }

    private static string Quote(string value)
    {
        var literal = new StringBuilder("\"");
        foreach (char character in value)
        {
            if (character is '\\' or '"')
                literal.Append('\\').Append(character);
            else if (char.IsControl(character))
                literal.Append("\\u").Append(((int)character).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
            else
                literal.Append(character);
        }
        return literal.Append('"').ToString();
    }
}
