namespace Inno.Text;

/// <summary>
/// Selects the typographic slant requested from a font face.
/// </summary>
public enum TextFontStyle
{
    /// <summary>
    /// Uses an upright face.
    /// </summary>
    Normal,
    /// <summary>
    /// Uses an italic face.
    /// </summary>
    Italic,
    /// <summary>
    /// Uses an oblique face.
    /// </summary>
    Oblique
}
